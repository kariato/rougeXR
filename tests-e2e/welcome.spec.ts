import { desktopClick, desktopFill, gameKey } from './ui-helpers';
import { expect, test } from '@playwright/test';
test('launches at a welcome screen and starts only after choosing New Game', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page.locator('#welcome-load')).toBeDisabled();
  await expect(page.locator('#welcome-status')).toContainText('Your first adventure awaits');
  await page.keyboard.press('Escape'); await page.keyboard.press('w');
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page.locator('#state-summary')).toContainText('Revision 0');
  await page.locator('#welcome').screenshot({ path: `test-results/welcome-${test.info().project.name}.png` });
  await page.locator('#welcome-new').click();
  await expect(page.getByRole('dialog')).toBeHidden();
  await page.keyboard.press('.');
  await expect(page.locator('#state-summary')).toContainText('Revision 1');
});
test('offers named games and autosave without silently restoring either', async ({ page }) => {
  await page.goto('/'); await page.locator('#welcome-new').click();
  await gameKey(page, '.'); await expect(page.locator('#state-summary')).toContainText('Revision 1');
  await desktopFill(page, '#save-name', 'The old adventure'); await desktopClick(page, '#save-local');
  await expect(page.locator('#saved-games')).toContainText('The old adventure');
  await gameKey(page, '.'); await expect(page.locator('#state-summary')).toContainText('Revision 2');
  await page.reload();
  await expect(page.locator('#welcome-saves')).toContainText('The old adventure');
  await expect(page.locator('#welcome-saves')).toContainText('Latest autosave');
  await expect(page.locator('#state-summary')).toContainText('Revision 0');
  await page.locator('#welcome-saves').selectOption({ label: 'The old adventure' });
  await page.locator('#welcome-load').click();
  await expect(page.getByRole('dialog')).toBeHidden();
  await expect(page.locator('#state-summary')).toContainText('Revision 1');
  await page.reload();
  await expect(page.locator('#welcome-saves')).toContainText('Latest autosave');
  await page.locator('#welcome-saves').selectOption({ label: 'Latest autosave' });
  await page.locator('#welcome-load').click();
  await expect(page.getByRole('dialog')).toBeHidden();
  await expect(page.locator('#state-summary')).toContainText('Revision 2');
});
test('keeps welcome available when a saved game is corrupt', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('rougexr.named-saves.v1', JSON.stringify([{ name: 'Broken save', json: '{}' }])));
  await page.goto('/');
  await expect(page.locator('#welcome-load')).toBeEnabled();
  await page.locator('#welcome-load').click();
  await expect(page.locator('#welcome-status')).toContainText('invalid or incompatible');
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.locator('#welcome-new').click();
  await expect(page.getByRole('dialog')).toBeHidden();
});

test('accepts a chosen seed and generates a new seed on welcome and restart', async ({ page }) => {
  await page.goto('/');
  await page.locator('#welcome-random').click();
  const random = Number(await page.locator('#welcome-seed').inputValue());
  expect(random).not.toBe(12345); expect(random).toBeGreaterThanOrEqual(0); expect(random).toBeLessThanOrEqual(4294967295);
  await page.locator('#welcome-seed').fill('43210'); await page.locator('#welcome-new').click();
  await expect(page.locator('#state-summary')).toContainText('Seed 43210');
  await expect(page.locator('#save-name')).toHaveValue(/\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2} · seed 43210/);
  await desktopClick(page, '#save-local');
  const saves = await page.evaluate(() => JSON.parse(localStorage.getItem('rougexr.named-saves.v1')!));
  expect(saves[0].name).toMatch(/\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2} · seed 43210/);
  await page.locator('.desktop-menu > summary').click(); await page.locator('#new-game').click();
  await expect(page.locator('#restart-seed')).toHaveValue('43210');
  await page.locator('#restart-seed').fill(''); await page.getByRole('button', { name: 'Keep playing' }).click();
  await expect(page.locator('#restart-confirm')).toBeHidden();
  await expect(page.locator('#state-summary')).toContainText('Seed 43210');
  await page.locator('#new-game').click();
  await page.locator('#restart-random').click();
  expect(await page.locator('#restart-seed').inputValue()).not.toBe('43210');
  await page.locator('#restart-seed').fill('9876'); await page.locator('#confirm-restart').click();
  await expect(page.locator('#state-summary')).toContainText('Seed 9876');
  await expect(page.locator('#save-name')).toHaveValue(/seed 9876$/);
});
